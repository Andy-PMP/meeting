"""Dataset report: how the kept invites spread across spec dimensions, lengths, and spend.

Writes docs/data-report.md (generated; don't edit by hand) and prints a summary.

    python pipeline\\report.py
"""

from __future__ import annotations

import statistics
from collections import Counter

from clean import masked_fraction
from generate import DUPLICATES, MODEL, PROMPT_VERSION, total_cost
from jsonl import read_jsonl
from paths import DOCS, INVITES, SPECS
from specs import (
    FORMATS,
    INDUSTRIES,
    LENGTHS,
    MEETING_TYPES,
    MESSINESS,
    SUBTLETY,
    TONES,
    VAGUENESS,
    ZOOM_FORMAT,
)

OUT = DOCS / "data-report.md"

DIMENSIONS = {
    "gen_hint": ["keep", "shorter", "email"],
    "subtlety": SUBTLETY,
    "meeting_type": [m[0] for m in MEETING_TYPES],
    "format": [*FORMATS, ZOOM_FORMAT],
    "industry": INDUSTRIES,
    "tone": TONES,
    "length": LENGTHS,
    "vagueness": VAGUENESS,
}


def build_report(invites: list[dict], specs: dict[str, dict]) -> tuple[str, list[str]]:
    """(markdown, list of spec values with zero invites)."""
    rows = [specs[i["spec_id"]] for i in invites if i["spec_id"] in specs]
    missing: list[str] = []
    md = [
        "# Data report",
        "",
        "Generated by `pipeline/report.py`. Don't edit by hand.",
        "",
        f"- Invites kept: **{len(invites)}** (duplicates dropped: {len(read_jsonl(DUPLICATES))})",
        f"- Model: `{MODEL}` · prompt: `{PROMPT_VERSION}`",
    ]
    usd, n = total_cost()
    md.append(f"- API spend: **${usd:.2f}** over {n} batch requests (50% batch discount applied)")

    for dim, values in DIMENSIONS.items():
        counts = Counter(r[dim] for r in rows)
        md += ["", f"## {dim}", "", "| value | invites |", "|---|---|"]
        for v in values:
            md.append(f"| {v} | {counts.get(v, 0)} |")
            if not counts.get(v):
                missing.append(f"{dim}={v}")

    mess = Counter(m for r in rows for m in r["messiness"])
    md += ["", "## messiness", "", "| quirk | invites |", "|---|---|"]
    md += [f"| (none) | {sum(1 for r in rows if not r['messiness'])} |"]
    for m in MESSINESS:
        md.append(f"| {m} | {mess.get(m, 0)} |")
        if not mess.get(m):
            missing.append(f"messiness={m}")

    md += ["", "## Word counts by requested length", "", "| length | n | min | median | max |"]
    md.append("|---|---|---|---|---|")
    for length in LENGTHS:
        words = [
            len(i["text"].split())
            for i in invites
            if specs.get(i["spec_id"], {}).get("length") == length
        ]
        if words:
            md.append(
                f"| {length} | {len(words)} | {min(words)} | "
                f"{statistics.median(words):g} | {max(words)} |"
            )

    # What the models won't see (pipeline/clean.py): join blocks, dial-ins, links, fwd headers.
    fractions = [masked_fraction(i["text"]) for i in invites]
    hit = [f for f in fractions if f > 0]
    md += ["", "## Boilerplate masked before modeling", ""]
    if hit:
        md += [
            f"- Invites with something masked: **{len(hit)}** of {len(invites)}",
            f"- Share of characters masked in those: median {statistics.median(hit):.0%}, "
            f"max {max(hit):.0%}",
            f"- Invites that are mostly boilerplate (over 40% masked): {sum(f > 0.4 for f in hit)}",
        ]
    else:
        md.append("- None")
    return "\n".join(md) + "\n", missing


def main() -> None:
    invites = read_jsonl(INVITES)
    specs = {s["spec_id"]: s for s in read_jsonl(SPECS)}
    md, missing = build_report(invites, specs)
    DOCS.mkdir(exist_ok=True)
    OUT.write_text(md, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT} ({len(invites)} invites)")
    if missing:
        print(f"{len(missing)} spec values have no invites yet: {', '.join(missing[:10])}...")
    else:
        print("Every spec value is represented.")


if __name__ == "__main__":
    main()
